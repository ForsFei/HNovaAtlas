using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Logging;
using Opc.Ua;
using Opc.Ua.Client;
using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;

namespace IndustrialOpcUa;

internal static class DemoHosts
{
    public static async Task StartServerAsync(IHost host, CancellationToken ct)
    {
        await host.StartAsync(ct);
        Task ready = host.Services.GetRequiredService<ServerReady>().Completion.Task;
        Task[] background = host.Services.GetServices<IHostedService>().OfType<BackgroundService>()
            .Select(service => service.ExecuteTask ?? Task.CompletedTask).ToArray();
        Task finished = await Task.WhenAny(background.Append(ready)).WaitAsync(ct);
        await finished; // Surface a hosted-service startup fault instead of waiting for readiness forever.
        if (finished != ready) throw new InvalidOperationException("Server stopped before readiness.");
    }

    public static IHost Server(string endpoint, string pki)
    {
        HostApplicationBuilder builder = Host.CreateApplicationBuilder([]);
        builder.Logging.SetMinimumLevel(LogLevel.Error);
        builder.Services.AddSingleton<ServerReady>();
        builder.Services.AddOpcUa().AddServer(options =>
        {
            options.ApplicationName = "HNovaOpcUaServer";
            options.ApplicationUri = "urn:localhost:HNovaOpcUaServer";
            options.ProductUri = "urn:hnova:opcua:demo";
            options.PkiRoot = pki;
            options.AutoAcceptUntrustedCertificates = false;
            options.IncludeUnsecurePolicyNone = false;
            options.DiagnosticsEnabled = false;
            options.EndpointUrls.Add(endpoint);
            options.OperationTimeoutMs = 5_000;
        }).AddNodeManager(DemoModel.NamespaceUri, DemoModel.Configure)
            .AddStartupTask((services, context, ct) =>
            {
                services.GetRequiredService<ServerReady>().Completion.TrySetResult();
                return ValueTask.CompletedTask;
            });
        return builder.Build();
    }

    public static IHost Client(string endpoint, string pki)
    {
        HostApplicationBuilder builder = Host.CreateApplicationBuilder([]);
        builder.Logging.SetMinimumLevel(LogLevel.Error);
        builder.Services.AddOpcUa().AddClient(options =>
        {
            options.ApplicationName = "HNovaOpcUaClient";
            options.ApplicationUri = "urn:localhost:HNovaOpcUaClient";
            options.ProductUri = "urn:hnova:opcua:demo";
            options.PkiRoot = pki;
            options.AutoAcceptUntrustedCertificates = false;
            options.LoadConfigurationOnStart = true;
            options.Session = new ManagedSessionOptions
            {
                CheckDomain = true,
                SessionName = "HNova loopback checks",
                SessionTimeout = TimeSpan.FromSeconds(30),
                ReconnectPolicy = new ReconnectPolicyOptions
                {
                    MaxRetries = 1, // 0 means unlimited, not disabled!
                    MaxTotalReconnectTime = TimeSpan.FromSeconds(5)
                }
            };
        }).AddDiscoveryAndConnect(options =>
        {
            options.DiscoveryUrl = endpoint;
            options.SecurityMode = MessageSecurityMode.SignAndEncrypt;
            options.SecurityPolicyUri = SecurityPolicies.Basic256Sha256;
        });
        return builder.Build();
    }

    // Only the public certificates generated by THIS run's peer are approved.
    // This is an isolated local bootstrap, not an approve-all-rejected policy.
    public static int TrustOwnPeer(string peerPki, string ownPki, string expectedName)
    {
        string destination = Path.Combine(ownPki, "trusted", "certs");
        Directory.CreateDirectory(destination);
        string[] files = Directory.GetFiles(Path.Combine(peerPki, "certs"), "*.der");
        if (files.Length == 0) throw new InvalidOperationException("No own peer certificate found.");
        foreach (string file in files)
        {
            using X509Certificate2 cert = X509CertificateLoader.LoadCertificateFromFile(file);
            if (cert.GetNameInfo(X509NameType.SimpleName, false) != expectedName)
                throw new InvalidOperationException("Unexpected locally generated certificate identity.");
            string digest = cert.GetCertHashString(HashAlgorithmName.SHA256);
            Console.WriteLine($"Trust local {expectedName}: SHA256 {digest}");
            File.Copy(file, Path.Combine(destination, digest + ".der"), overwrite: false);
        }
        return files.Length;
    }
}

internal sealed class ServerReady
{
    public TaskCompletionSource Completion { get; } = new(TaskCreationOptions.RunContinuationsAsynchronously);
}
