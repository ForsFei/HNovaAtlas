import { execFileSync, spawn } from "node:child_process";
import { once } from "node:events";
import { mkdtempSync, readFileSync, writeFileSync, renameSync, unlinkSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const output = fileURLToPath(new URL("./src/generated-query.d.ts", import.meta.url));
const before = (() => { try { return readFileSync(output, "utf8"); } catch (error) {
  if (error.code === "ENOENT") return null;
  throw error;
} })();
const work = mkdtempSync(join(tmpdir(), "atlas-query-contract-"));
execFileSync("dotnet", ["build", "examples/web-quality-trace/lesson-03", "--nologo"],
  { cwd: root, stdio: "pipe" });
const app = join(root, "examples/web-quality-trace/lesson-03/bin/Debug/net10.0/QualityTrace.Storage.dll");
const server = spawn("dotnet", [app, "--TraceDb", join(work, "trace.db"),
  "--Contract:Enabled", "true", "--Review:Enabled", "false", "--Events:Enabled", "false",
  "--Live:Enabled", "false", "--urls", "http://127.0.0.1:0"],
{ cwd: work, windowsHide: true });
const exited = once(server, "exit");
let log = "";
server.stdout.setEncoding("utf8").on("data", value => { log += value; });
server.stderr.setEncoding("utf8").on("data", value => { log += value; });

try {
  let origin;
  for (let i = 0; i < 150; i++) {
    origin = log.match(/Now listening on: (http:\/\/127\.0\.0\.1:\d+)/)?.[1];
    if (origin) break;
    if (server.exitCode !== null) throw new Error("Contract API exited during startup.");
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  if (!origin) throw new Error("Contract API startup timed out.");
  const response = await fetch(origin + "/openapi/v1.json", { signal: AbortSignal.timeout(10000) });
  if (!response.ok) throw new Error("Unable to read the query contract.");
  const document = await response.json();
  const source = "// Generated by npm run generate:contract. Edit the API metadata, then regenerate.\n"
    + astToString(await openapiTS(document));
  if (process.argv.includes("--check")) {
    if (before !== source) throw new Error("Query types are stale. Run npm run generate:contract and review the diff.");
    console.log("Query contract types match the current backend.");
  } else if (before !== source) {
    let current = null;
    try { current = readFileSync(output, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
    if (current !== before) throw new Error("Generated file changed concurrently.");
    const temporary = output + "." + process.pid + ".tmp";
    try {
      writeFileSync(temporary, source, { flag: "wx" });
      renameSync(temporary, output);
    } finally {
      try { unlinkSync(temporary); } catch (error) { if (error.code !== "ENOENT") throw error; }
    }
    console.log("Updated src/generated-query.d.ts");
  } else {
    console.log("Query contract types already current.");
  }
} finally {
  if (server.exitCode === null && server.signalCode === null) server.kill();
  await exited;
}
